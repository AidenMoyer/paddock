"""Generate a small but realistic media tree for tests and the dev demo (ffmpeg + Pillow only)."""

from __future__ import annotations

import base64
import io
import os
import struct
import subprocess
import time
from pathlib import Path

import numpy as np
from PIL import Image


def _ff(*args: str) -> None:
    subprocess.run(["ffmpeg", "-v", "error", "-y", *args], check=True)


def video(path: Path, seconds: float = 4, size: str = "640x360", vcodec: str = "libx264", acodec: str = "aac",
          pattern: str = "testsrc2", freq: int = 440, extra: list[str] | None = None) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    _ff("-f", "lavfi", "-i", f"{pattern}=size={size}:rate=30",
        "-f", "lavfi", "-i", f"sine=frequency={freq}:duration={seconds}",
        "-c:v", vcodec, "-pix_fmt", "yuv420p", *(["-preset", "ultrafast"] if vcodec in ("libx264", "libx265") else []),
        *(["-x265-params", "log-level=error"] if vcodec == "libx265" else []),
        "-g", "30", "-c:a", acodec, "-t", str(seconds), *(extra or []), str(path))
    return path


def photo(path: Path, color=(200, 80, 40), taken="2024:07:04 18:30:00", gps=(37.7749, -122.4194), size=(1200, 800)) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    arr = np.zeros((size[1], size[0], 3), np.uint8)
    arr[..., 0] = np.linspace(color[0], 255 - color[0], size[0])[None, :]
    arr[..., 1] = np.linspace(color[1], 255 - color[1], size[1])[:, None]
    arr[..., 2] = color[2]
    im = Image.fromarray(arr)
    exif = Image.Exif()
    exif[0x010F] = "Samsung"
    exif[0x0110] = "Galaxy S25"
    exif[0x0132] = taken
    exif.get_ifd(0x8769)[36867] = taken

    def dms(v):
        v = abs(v)
        d = int(v)
        m = int((v - d) * 60)
        s = round(((v - d) * 60 - m) * 60 * 100)
        return ((d, 1), (m, 1), (s, 100))

    if gps:
        g = exif.get_ifd(0x8825)
        g[1] = "N" if gps[0] >= 0 else "S"
        g[2] = tuple(x[0] / x[1] for x in dms(gps[0]))
        g[3] = "E" if gps[1] >= 0 else "W"
        g[4] = tuple(x[0] / x[1] for x in dms(gps[1]))
    im.save(path, "JPEG", exif=exif, quality=85)
    return path


def mp3(path: Path, title: str, artist: str, album: str, track: int, freq: int = 330) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    _ff("-f", "lavfi", "-i", f"sine=frequency={freq}:duration=3", "-c:a", "libmp3lame", "-b:a", "128k", str(path))
    from mutagen.easyid3 import EasyID3

    try:
        tags = EasyID3(path)
    except Exception:
        from mutagen.id3 import ID3

        ID3().save(path)
        tags = EasyID3(path)
    tags.update({"title": title, "artist": artist, "album": album, "tracknumber": str(track), "genre": "Rock",
                 "date": "2019"})
    tags.save()
    return path


def stl_box(path: Path, sx=40.0, sy=20.0, sz=10.0, cyl: bool = False) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    tris = []
    if cyl:
        n = 48
        for i in range(n):
            a0, a1 = 2 * np.pi * i / n, 2 * np.pi * (i + 1) / n
            p0 = (sx * np.cos(a0), sx * np.sin(a0))
            p1 = (sx * np.cos(a1), sx * np.sin(a1))
            tris += [((0, 0, 0), (p1[0], p1[1], 0), (p0[0], p0[1], 0)),
                     ((0, 0, sz), (p0[0], p0[1], sz), (p1[0], p1[1], sz)),
                     ((p0[0], p0[1], 0), (p1[0], p1[1], 0), (p1[0], p1[1], sz)),
                     ((p0[0], p0[1], 0), (p1[0], p1[1], sz), (p0[0], p0[1], sz))]
    else:
        v = [(x, y, z) for x in (0, sx) for y in (0, sy) for z in (0, sz)]
        faces = [(0, 2, 3, 1), (4, 5, 7, 6), (0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)]
        for a, b, c, d in faces:
            tris += [(v[a], v[b], v[c]), (v[a], v[c], v[d])]
    with path.open("wb") as f:
        f.write(b"paddock test".ljust(80, b" "))
        f.write(struct.pack("<I", len(tris)))
        for t in tris:
            f.write(struct.pack("<3f", 0, 0, 0))
            for p in t:
                f.write(struct.pack("<3f", *p))
            f.write(b"\0\0")
    return path


def gcode(path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    im = Image.new("RGB", (220, 124), (255, 120, 60))
    buf = io.BytesIO()
    im.save(buf, "PNG")
    b64 = base64.b64encode(buf.getvalue()).decode()
    lines = [b64[i:i + 78] for i in range(0, len(b64), 78)]
    thumb = "\n".join(["; thumbnail begin 220x124 %d" % len(b64)] + [f"; {ln}" for ln in lines] + ["; thumbnail end"])
    body = "\n".join(f"G1 X{10 + i % 50} Y{10 + (i * 7) % 50} E{i * 0.05:.3f}" for i in range(500))
    path.write_text(f"""; generated by PrusaSlicer 2.8.1+win64 on 2026-05-01
{thumb}
M104 S215
G28
{body}
; filament used [mm] = 1234.56
; filament used [g] = 3.71
; estimated printing time (normal mode) = 1h 2m 3s
; filament_type = PETG
; layer_height = 0.2
; nozzle_diameter = 0.4
; printer_model = MK4S
; fill_density = 20%
""")
    return path


def step(path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("""ISO-10303-21;
HEADER;
FILE_DESCRIPTION(('turbo flange'),'2;1');
FILE_NAME('flange.step','2026-04-02T10:11:12',('Aiden'),('Go Fast'),'ST-DEVELOPER v20','Autodesk Fusion 360','');
FILE_SCHEMA(('AP242_MANAGED_MODEL_BASED_3D_ENGINEERING_MIM_LF { 1 0 10303 442 1 1 4 }'));
ENDSEC;
DATA;
#1=CARTESIAN_POINT('',(0.,0.,0.));
ENDSEC;
END-ISO-10303-21;
""")
    return path


def kicad(path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('(kicad_pcb (version 20240108) (generator "pcbnew")\n  (title_block (title "ECU breakout") (rev "B") (company "Go Fast"))\n'
                    '  (layers (0 "F.Cu" signal) (31 "B.Cu" signal) (44 "Edge.Cuts" user))\n)\n')
    return path


def red_clip(root: Path, cam="A", reel=1, clip=1, mmdd="0712", rand="AB", proxy=True) -> Path:
    name = f"{cam}{reel:03d}_C{clip:03d}_{mmdd}{rand}"
    rdc = root / f"{cam}{reel:03d}_{mmdd}{rand}.RDM" / f"{name}.RDC"
    rdc.mkdir(parents=True, exist_ok=True)
    for span in (1, 2):
        (rdc / f"{name}_{span:03d}.R3D").write_bytes(b"\x00\x00\x00\x40RED2" + os.urandom(4096))
    (rdc / f"{name}.RMD").write_text('<?xml version="1.0"?><rmd><iso>800</iso><kelvin>5600</kelvin><tint>0</tint></rmd>')
    if proxy:
        video(rdc / f"{name}.mov", seconds=3, size="1024x540", pattern="smptehdbars", freq=520)
    return rdc / f"{name}_001.R3D"


def build(root: Path) -> dict[str, Path]:
    """Create the full fixture tree. Returns library roots by kind."""
    libs = {k: root / k for k in ("movies", "shows", "music", "photos", "home_videos", "red", "engineering")}
    video(libs["movies"] / "The.Matrix.1999.1080p.BluRay.x264.mkv", seconds=8, vcodec="libx265", pattern="mandelbrot")
    video(libs["movies"] / "Big Buck (2008)" / "Big Buck (2008).mp4", seconds=5, pattern="testsrc2")
    video(libs["shows"] / "Garage Builds" / "Season 1" / "Garage.Builds.S01E02.Turbo.Time.mp4", seconds=4,
          pattern="rgbtestsrc")
    video(libs["shows"] / "Garage Builds" / "Season 1" / "Garage.Builds.S01E01.Pilot.mp4", seconds=4, pattern="testsrc")
    mp3(libs["music"] / "The Pistons" / "Redline" / "01 - Launch Control.mp3", "Launch Control", "The Pistons",
        "Redline", 1)
    mp3(libs["music"] / "The Pistons" / "Redline" / "02 - Boost.mp3", "Boost", "The Pistons", "Redline", 2, freq=392)
    photo(libs["photos"] / "Camera" / "20240704_183000.jpg")
    photo(libs["photos"] / "Camera" / "20240705_101500.jpg", color=(40, 160, 200), taken="2024:07:05 10:15:00",
          gps=(37.80, -122.27))
    photo(libs["photos"] / "Camera" / "Screenshot_20250101.jpg", color=(90, 90, 90), taken="2025:01:01 09:00:00", gps=None)
    video(libs["home_videos"] / "2024" / "launch-day.mp4", seconds=4, pattern="testsrc2",
          extra=["-metadata", "creation_time=2024-07-04T19:00:00Z", "-metadata", "location=+37.7749-122.4194/"])
    red_clip(libs["red"])
    red_clip(libs["red"], clip=2, rand="AB")
    eng = libs["engineering"]
    step(eng / "Turbo Manifold" / "flange_v2.step")
    stl_box(eng / "Turbo Manifold" / "STL" / "flange_v3.stl", cyl=True, sx=30, sz=8)
    stl_box(eng / "Turbo Manifold" / "STL" / "flange_v2.stl", cyl=True, sx=30, sz=6)
    gcode(eng / "Turbo Manifold" / "G-code" / "flange_v3_0.2mm_PETG_MK4S.gcode")
    kicad(eng / "ECU" / "breakout.kicad_pcb")
    inbox = eng / "_Inbox" / "Go Kart"
    stl_box(inbox / "axle_spacer.stl", sx=25, sy=25, sz=12)
    old = time.time() - 3600
    os.utime(inbox / "axle_spacer.stl", (old, old))
    return libs


if __name__ == "__main__":
    import sys

    out = Path(sys.argv[1] if len(sys.argv) > 1 else "demo-media")
    print({k: str(v) for k, v in build(out).items()})
