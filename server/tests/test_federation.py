HERE = Path(__file__).resolve().parents[1]
MARKER = b"PADDOCK-PLAINTEXT-MARKER-7f3a9c"


def _start(name: str, port: int, root: Path, role: str = "server") -> subprocess.Popen:
    env = dict(os.environ)
    env.update({"PADDOCK_DATA_DIR": str(root / "data"), "PADDOCK_MEDIA_ROOTS": str(root / "media"), "PADDOCK_TLS": "1",
                "PADDOCK_DEV": "1", "PADDOCK_HOST": "127.0.0.1", "PADDOCK_PORT": str(port), "PADDOCK_WG_ENABLED": "0",
                "PADDOCK_ROLE": role, "PADDOCK_HOSTNAMES": "localhost,127.0.0.1"})
    (root / "media").mkdir(parents=True, exist_ok=True)
    log = (root / f"{name}.log").open("wb")
    return subprocess.Popen([sys.executable, "-m", "paddock"], cwd=HERE, env=env, stdout=log, stderr=subprocess.STDOUT)


def _client(port: int) -> httpx.Client:
    return httpx.Client(base_url=f"https://127.0.0.1:{port}", verify=False, headers={"x-paddock": "1"}, timeout=60)


def _wait_up(c: httpx.Client):
    for _ in range(150):
        try:
            if c.get("/api/health").status_code == 200:
                return
        except httpx.HTTPError:
            pass
        time.sleep(0.2)
    raise AssertionError("server didn't start")


def _wait_jobs(c: httpx.Client, timeout=120) -> list:
    end = time.time() + timeout
    while time.time() < end:
        j = c.get("/api/jobs").json()
        if not j["active"]:
            return j["recent"]
        time.sleep(0.3)
    raise AssertionError("jobs still running")


