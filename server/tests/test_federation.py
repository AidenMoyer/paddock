def test_link_by_invite(pair):
    a, b = pair["a"], pair["b"]
    inv = b.post("/api/federation/invite", json={"backup_quota_gb": 1, "libraries": []}).json()
    assert inv["invite"].startswith("pdk-link:") and len(inv["safety_words"].split()) == 6
    pre = a.post("/api/federation/inspect", json={"invite": inv["invite"]}).json()
    assert pre["safety_words"] == inv["safety_words"] and pre["name"] == "Offsite Node" and pre["role"] == "node"
    r = a.post("/api/federation/accept", json={"invite": inv["invite"]})
    assert r.status_code == 200, r.text
    fa, fb = a.get("/api/federation").json(), b.get("/api/federation").json()
    assert fa["peers"][0]["name"] == "Offsite Node" and fa["peers"][0]["their_grants"]["backup_quota_gb"] == 1
    assert fb["peers"][0]["name"] == "Home" and fb["peers"][0]["our_grants"]["backup_quota_gb"] == 1
    # one-time: reusing the invite fails
    assert a.post("/api/federation/accept", json={"invite": inv["invite"]}).status_code == 400  # already linked
    pair["peer_on_a"] = fa["peers"][0]["id"]
    pair["peer_on_b"] = fb["peers"][0]["id"]


def test_tampered_invite_refused(pair):
    a, b = pair["a"], pair["b"]
    inv = b.post("/api/federation/invite", json={"backup_quota_gb": 0}).json()["invite"]
    raw = inv[len("pdk-link:"):]
    data = json.loads(base64.urlsafe_b64decode(raw + "=" * (-len(raw) % 4)))
    data["node_id"] = "0" * 64  # attacker swaps in their own identity
    bad = "pdk-link:" + base64.urlsafe_b64encode(json.dumps(data).encode()).decode().rstrip("=")
    r = a.post("/api/federation/accept", json={"invite": bad})
    assert r.status_code == 400 and "identity" in r.json()["detail"].lower()


def test_peer_token_cannot_use_user_api(pair):
    b = pair["b"]
    import sqlite3

    con = sqlite3.connect(pair["root"] / "a" / "data" / "paddock.db")
    token = con.execute("SELECT token_out FROM peers").fetchone()[0]
    con.close()
    h = {"Authorization": f"Bearer {token}"}
    raw = httpx.Client(base_url=str(b.base_url), verify=False)
    assert raw.get("/api/home", headers=h).status_code == 401
    assert raw.get("/api/admin/overview", headers=h).status_code == 401
    assert raw.get("/api/peer/vault/usage", headers=h).status_code == 200


def test_encrypted_backup_restore_verify(pair):
    a, b, root = pair["a"], pair["b"], pair["root"]
    a.put("/api/backup/config", json={"enabled": True, "targets": [pair["peer_on_a"]], "libraries": [pair["lib_id"]], "include_database": True})
    assert a.post("/api/backup/run").status_code == 200
    jobs = _wait_jobs(a)
    first = next(j for j in jobs if j["kind"] == "backup")
    assert first["state"] == "done", first
    assert "3 files" in first["message"]
    # the backup server holds only ciphertext
    vault_files = [p for p in (root / "b" / "data" / "vault").rglob("*") if p.is_file()]
    assert vault_files
    for p in vault_files:
        data = p.read_bytes()
        assert MARKER not in data and b"axle" not in data and data[:4] == b"PDK1"
    # incremental: nothing new to send (except the database snapshot)
    a.post("/api/backup/run")
    second = next(j for j in _wait_jobs(a) if j["kind"] == "backup")
    sent_mb = float(second["message"].split("sent ")[1].split(" MB")[0])
    assert sent_mb < 1.0, second["message"]
    snaps = a.get(f"/api/backup/snapshots?peer={pair['peer_on_a']}").json()
    assert len(snaps) >= 1 and snaps[0]["files"] == 3
    r = a.post("/api/backup/restore", json={"peer": pair["peer_on_a"], "snapshot": snaps[0]["name"]}).json()
    restored = next(j for j in _wait_jobs(a) if j["kind"] == "restore")
    assert restored["state"] == "done", restored
    dest = Path(r["dest"]) / "Engineering" / "Kart"
    for name in ("axle.stl", "photo.jpg", "notes.gcode"):
        assert (dest / name).read_bytes() == (pair["lib_root"] / "Kart" / name).read_bytes()
    assert (Path(r["dest"]) / "paddock-database.db").exists()
    a.post("/api/backup/verify", json={"peer": pair["peer_on_a"], "snapshot": snaps[0]["name"]})
    v = next(j for j in _wait_jobs(a) if j["kind"] == "verify")
    assert v["state"] == "done" and "all decrypted" in v["message"]


def test_quota_enforced(pair):
    b = pair["b"]
    b.patch(f"/api/federation/peers/{pair['peer_on_b']}", json={"grants": {"backup_quota_gb": 0.000001}})
    a = pair["a"]
    (pair["lib_root"] / "Kart" / "big.stl").write_bytes(os.urandom(3_000_000))
    a.post(f"/api/libraries/{pair['lib_id']}/scan")
    _wait_jobs(a)
    a.post("/api/backup/run")
    j = next(j for j in _wait_jobs(a) if j["kind"] == "backup")
    assert "quota" in (j["message"] or "").lower()
    b.patch(f"/api/federation/peers/{pair['peer_on_b']}", json={"grants": {"backup_quota_gb": 1}})


def test_library_sharing_through_proxy(pair):
    a, b = pair["a"], pair["b"]
    # A shares its engineering library with B; B browses it through its own API
    a.patch(f"/api/federation/peers/{pair['peer_on_a']}", json={"grants": {"backup_quota_gb": 0, "libraries": [pair["lib_id"]]}})
    items = b.get(f"/api/federation/peers/{pair['peer_on_b']}/items?limit=50").json()
    titles = {i["title"] for i in items}
    assert "axle" in titles and all("path" not in i for i in items)
    stl = next(i for i in items if i["title"] == "axle")
    r = b.get(f"/api/federation/peers/{pair['peer_on_b']}/items/{stl['id']}/file", headers={"Range": "bytes=0-79"})
    assert r.status_code == 206 and len(r.content) == 80
    t = b.get(f"/api/federation/peers/{pair['peer_on_b']}/items/{stl['id']}/thumb")
    assert t.status_code == 200 and t.headers["content-type"] == "image/webp"
    # unshare → access gone
    a.patch(f"/api/federation/peers/{pair['peer_on_a']}", json={"grants": {"backup_quota_gb": 0, "libraries": []}})
    assert b.get(f"/api/federation/peers/{pair['peer_on_b']}/items?limit=50").json() == []


def test_unlink_both_sides(pair):
    a, b = pair["a"], pair["b"]
    assert a.delete(f"/api/federation/peers/{pair['peer_on_a']}").status_code == 200
    assert a.get("/api/federation").json()["peers"] == []
    assert b.get("/api/federation").json()["peers"] == []
